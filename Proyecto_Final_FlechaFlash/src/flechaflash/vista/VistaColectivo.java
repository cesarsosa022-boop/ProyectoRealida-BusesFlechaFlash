    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
        try{
            String matricula = jtfMatricula.getText().trim();
            String marca = jtfMarca.getText().trim();
            String modeloBus = jtfModelo.getText().trim();
            int capacidad = (int) jsCapacidadAsientos.getValue();
            String chofer = jtfChoferAsignado.getText().trim();
            boolean estado = jcbEstado.isSelected();
            
            if (matricula.isEmpty() || marca.isEmpty() || modeloBus.isEmpty() || chofer.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete todos los campos obligatorios.");
                return;
            }

            if (capacidad <= 0) {
                JOptionPane.showMessageDialog(this, "La capacidad de asientos no puede ser menor a 1.");
                return;
            }
            Colectivo nuevoColectivo = new Colectivo(matricula, marca, modeloBus, capacidad, chofer, estado);
            colectivoData.guardarColectivo(nuevoColectivo);

            JOptionPane.showMessageDialog(this, "Colectivo guardado correctamente. Asientos generados.");
            formatearCampos();
            cargarTabla();
            

        }catch(Exception e){
            JOptionPane.showMessageDialog(this,"Error al guardar el colectivo"+e.getMessage(),"Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jbGuardarActionPerformed

    private void jbBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbBuscarActionPerformed
        if (jtfIDColectivo.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese un ID numerico para buscar.");
                return;
            }
        try {
            int id = Integer.parseInt(jtfIDColectivo.getText().trim());
            Colectivo colectivo = colectivoData.buscarColectivo(id);

            if (colectivo != null) {
                jtfMatricula.setText(colectivo.getMatricula());
                jtfMarca.setText(colectivo.getMarca());
                jtfModelo.setText(colectivo.getModelo());
                jsCapacidadAsientos.setValue(colectivo.getCapacidad());
                jtfChoferAsignado.setText(colectivo.getChofer());
                jcbEstado.setSelected(colectivo.isEstado());

                jbEditar.setEnabled(true);
                jbEliminar.setEnabled(true);
                if (colectivo.isEstado()) {
                    jbBajaLogica.setEnabled(true);
                    jbAltaLogica.setEnabled(false);
                } else {
                    jbBajaLogica.setEnabled(false);
                    jbAltaLogica.setEnabled(true);
                }
                jbGuardar.setEnabled(false);
            } else {
                JOptionPane.showMessageDialog(this, "No se encontro ningun colectivo con el ID especificado.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un ID numerico valido para buscar.");
        }
    }//GEN-LAST:event_jbBuscarActionPerformed

    private void jbEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEliminarActionPerformed
        if (jtfIDColectivo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un colectivo de la tabla para eliminar.");
            return;
        }
        int confirm= JOptionPane.showConfirmDialog(this, "¿Esta seguro de eliminar este colectivo?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (confirm== JOptionPane.YES_OPTION) {
            
            try {
                
                int id= Integer.parseInt(jtfIDColectivo.getText().trim());
                colectivoData.borrarColectivo(id);
                JOptionPane.showMessageDialog(this, "Colectivo eliminado fisicamente de la base de datos.");
                formatearCampos();
                cargarTabla();
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar (puede haber viajes asociados): " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jbEliminarActionPerformed

