    private void jbActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbActualizarActionPerformed
        try {
             if(jtfIDColectivo.getText().trim().isEmpty()){
             JOptionPane.showMessageDialog(this,"Seleccione un colectivo de la tabla para actualizar");
             return;
            }
            int id = Integer.parseInt(jtfIDColectivo.getText().trim());
            String matricula= jtfMatricula.getText().trim();
            String marca= jtfMarca.getText().trim();
            String modeloBus=jtfModelo.getText().trim();
            int capacidad = (int) jsCapacidadAsientos.getValue();
            String chofer = jtfChoferAsignado.getText().trim();
            boolean estado= jcbEstado.isSelected();

            if (matricula.isEmpty() || marca.isEmpty() || modeloBus.isEmpty() || chofer.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Los campos no pueden quedar en blanco.");
                return;
            }


            Colectivo colectivoMod = new Colectivo(id, matricula, marca, modeloBus, capacidad, chofer, estado);
            colectivoData.modificarColectivo(colectivoMod);

            JOptionPane.showMessageDialog(this, "Colectivo actualizado correctamente");
            formatearCampos();
            cargarTabla();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jbActualizarActionPerformed

